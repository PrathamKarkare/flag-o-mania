// Turn each "code|name|..." string into an object.
// .map() runs a function on every item and gives back a NEW array of results.
const flagList = RAW_COUNTRIES.map(function (line) {
  const parts = line.split("|");          // "jp|Japan|Asia|1|" -> ["jp","Japan","Asia","1",""]
  return {
    code: parts[0],
    country: parts[1],
    continent: parts[2],
    tier: Number(parts[3]),               // "1" (text) -> 1 (a real number)
    altNames: parts[4] ? parts[4].split(";") : [],   // "uk;britain" -> ["uk","britain"]
    image: "https://flagcdn.com/w320/" + parts[0] + ".png",
  };
});
